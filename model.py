    def _solve_with_sympy(self, problem: str) -> Optional[str]:
        """Решает математику через sympy"""
        try:
            x, y, z = symbols('x y z')
            
            # Линейные уравнения
            if '=' in problem and 'x' in problem:
                # Простой парсер
                parts = problem.split('=')
                left = parts[0].replace('реши', '').replace(' ', '')
                right = parts[1].replace(' ', '')
                
                # Замена ^ на **
                left = left.replace('^', '**').replace('²', '**2').replace('³', '**3')
                right = right.replace('^', '**').replace('²', '**2').replace('³', '**3')
                
                eq = Eq(eval(left), eval(right))
                sol = solve(eq, x)
                
                if len(sol) == 1:
                    return f"✅ **Решение:**\n\nx = {sol[0]}"
                else:
                    return f"✅ **Решения:**\n\n{', '.join([f'x = {s}' for s in sol])}"
        except:
            return None
    
