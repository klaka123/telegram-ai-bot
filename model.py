    def _solve_with_sympy(self, problem):
        """Решает математические выражения через sympy"""
        x, y, z = symbols('x y z')
        
        if 'реши' in problem or 'найди' in problem or 'вычисли' in problem:
            
            if 'x' in problem and '=' in problem:
                try:
                    # Простой парсинг уравнений
                    parts = problem.split('=')
                    left = parts[0].replace('реши', '').replace(' ', '')
                    right = parts[1].replace(' ', '')
                    
                    # Заменяем ^ на **
                    left = left.replace('^', '**')
                    right = right.replace('^', '**')
                    
                    eq = Eq(eval(left), eval(right))
                    solution = solve(eq, x)
                    
                    if len(solution) == 1:
                        return f"✅ **Решение:**\n\nx = {solution[0]}"
                    else:
                        solutions = ', '.join([f"x = {s}" for s in solution])
                        return f"✅ **Решения:**\n\n{solutions}"
                except:
                    pass
            
            if 'производн' in problem:
                try:
                    expr_str = problem.replace('найди', '').replace('производную', '').replace(' ', '')
                    expr_str = expr_str.replace('^', '**')
                    
                    if expr_str and expr_str != '':
                        f = eval(expr_str)
                        df = diff(f, x)
                        return f"📈 **Производная:**\n\nf'(x) = {df}"
                except:
                    pass
            
            if 'интеграл' in problem:
                try:
                    expr_str = problem.replace('найди', '').replace('интеграл', '').replace(' ', '')
                    expr_str = expr_str.replace('dx', '').replace('^', '**')
                    
                    if expr_str and expr_str != '':
                        f = eval(expr_str)
                        F = integrate(f, x)
                        return f"∫ **Интеграл:**\n\n∫ f(x) dx = {F} + C"
                except:
                    pass
        
        return None
    
